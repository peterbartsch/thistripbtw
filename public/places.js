/* places.js v2 — type a place, pick it from a list.
 *
 * Shared by /new, /quick, /quicktree and the trip editor. The API is unchanged from v1:
 * attachSuggest(input, {near, onPick, minChars, anchor}) — so the four call sites did not move.
 *
 * WHAT CHANGED AND WHY (audit 2026-07-29, measured live): v1 sent every query to Nominatim,
 * and Nominatim is a geocoder, not an autocompleter. It has no prefix matching — "sacram"
 * returned a street in Portugal, "lake ta" returned Lake County, Minnesota — no typo
 * tolerance ("san fransisco" → three villages in Ecuador), and it fame-ranks, so "yosemite"
 * put Sydney, Australia first. The plumbing was fine; the engine was wrong for the job.
 *
 * v2 is LOCAL-FIRST: /places-index.json (40k cities, towns and airports; generated by
 * scripts/build-places-index.mjs; GeoNames CC-BY + OurAirports) is lazy-loaded on first
 * focus and searched on every keystroke — instant, prefix-correct, typo-tolerant, ranked by
 * population × proximity, with the launch market favoured (D-002). Nominatim remains the
 * long tail: addresses and obscure POIs arrive ~a second later and are APPENDED, never
 * reordering what is already under the finger. Same-origin static data: no new third party,
 * nothing about the person leaves the page (D-016 intact).
 */
(function (global) {
  "use strict";

  var NET_MIN = 4, NET_DEBOUNCE = 350, MAX_LOCAL = 5, MAX_NET = 3;

  /* ── the local index: one fetch, shared by every input on the page ────────────────────── */
  var IDX = null, IDX_PROMISE = null;
  var REGION_NAME = null;
  try { REGION_NAME = new Intl.DisplayNames(["en"], { type: "region" }); } catch (e) {}

  function countryName(cc) {
    if (cc === "US") return "";                     // home market: "Moab, UT" needs no country
    try { return REGION_NAME ? REGION_NAME.of(cc) : cc; } catch (e) { return cc; }
  }
  function norm(s) {
    s = s.toLowerCase();
    try { s = s.normalize("NFD").replace(/[̀-ͯ]/g, ""); } catch (e) {}
    return s;
  }

  function loadIndex() {
    if (IDX_PROMISE) return IDX_PROMISE;
    IDX_PROMISE = fetch("/places-index.json?v=2", { headers: { accept: "application/json" } })
      .then(function (r) { return r.ok ? r.json() : null; })
      .then(function (j) {
        if (!j || !j.rows) return null;
        // [name, region, cc, lat, lng, weight, kind, extra?] → search rows with a normalised
        // name. Buckets by first letter keep the typo pass from scanning all 40k rows.
        var rows = [], buckets = {}, codes = {};
        for (var i = 0; i < j.rows.length; i++) {
          var r = j.rows[i];
          var row = { name: r[0], region: r[1], cc: r[2], lat: r[3], lng: r[4],
                      w: r[5] / 10, kind: r[6], iata: r[7] || null, icao: r[8] || null,
                      n: norm(r[0]) };
          rows.push(row);
          var b = row.n.charAt(0);
          (buckets[b] || (buckets[b] = [])).push(row);
          // Codes are indexed SEPARATELY from names, because they do not agree: "ORD" is
          // "Chicago O'Hare", "EWR" is "Newark", "MCO" is "Orlando". Bucketing by name alone
          // is what made those three unreachable — see searchLocal.
          // IATA (3) and ICAO (4) share one map: different lengths, so they cannot collide.
          for (var ci = 0; ci < 2; ci++) {
            var code = ci ? row.icao : row.iata;
            if (!code) continue;
            var c = code.toLowerCase();
            if (!codes[c] || row.w > codes[c].w) codes[c] = row;
          }
        }
        IDX = { rows: rows, buckets: buckets, codes: codes };
        return IDX;
      })
      .catch(function () { return null; });
    return IDX_PROMISE;
  }

  /* one edit (substitution, insertion, deletion, adjacent swap) — enough for fat thumbs */
  function withinOneEdit(a, b) {
    var la = a.length, lb = b.length;
    if (Math.abs(la - lb) > 1) return false;
    var i = 0, j = 0, edits = 0;
    while (i < la && j < lb) {
      if (a.charAt(i) === b.charAt(j)) { i++; j++; continue; }
      if (++edits > 1) return false;
      if (la === lb) {
        if (a.charAt(i + 1) === b.charAt(j) && a.charAt(i) === b.charAt(j + 1)) { i += 2; j += 2; }
        else { i++; j++; }
      } else if (la > lb) i++;
      else j++;
    }
    return edits + (la - i) + (lb - j) <= 1;
  }

  /**
   * Score a row against normalised query tokens. Every token must land — as a prefix of one
   * of the name's words, or (last token, ≥4 chars) within one edit of one. IATA codes match
   * exactly: "sfo" must be one cheap hit.
   */
  function scoreRow(row, qtokens, qjoined, near) {
    if ((row.iata && qjoined === row.iata.toLowerCase()) ||
        (row.icao && qjoined === row.icao.toLowerCase()))
      return 40 + row.w;                             // typed the code; done
    var words = row.n.split(/[\s'-]+/), score = 0;
    for (var t = 0; t < qtokens.length; t++) {
      var q = qtokens[t], best = 0;
      for (var wi = 0; wi < words.length; wi++) {
        var w = words[wi];
        if (w.substring(0, q.length) === q) { best = Math.max(best, wi === 0 ? 2.5 : 2); }
        else if (t === qtokens.length - 1 && q.length >= 4 &&
                 withinOneEdit(q, w.substring(0, Math.min(w.length, q.length + 1))))
          best = Math.max(best, 1);
      }
      if (!best) return 0;
      score += best;
    }
    if (row.n === qjoined) score += 4;               // typed the whole thing
    // an airport matched by a word buried mid-name ("yosemite" in "Fresno Yosemite Intl")
    // must not bring its jumbo weight — that outranked Yosemite's actual towns
    score += (row.iata && score < 3 * qtokens.length) ? Math.min(row.w, 2.5)
                                                      : row.w;
    if (near) {
      var d = Math.hypot(row.lat - near.lat, row.lng - near.lng);   // degrees ≈ good enough
      score += d < 1 ? 3 : d < 5 ? 2 : d < 15 ? 1 : 0;
    } else if (row.cc === "US") score += 1.2;        // launch market, absent better signal
    return score;
  }

  function searchLocal(query, near) {
    if (!IDX) return [];
    var qn = norm(query.trim());
    var qtokens = qn.split(/\s+/).filter(Boolean);
    if (!qtokens.length) return [];
    var qjoined = qtokens.join(" ");
    // candidate set: rows whose name starts with the first token's letter — plus, because a
    // typo can sit in the first letter, everything, when that pass comes up thin. (v2.0.1:
    // the first cut of this loop cleared its results after the SECOND pass too, so any query
    // with fewer than three matches — "moab" — returned nothing. Scan is now a function and
    // the widening is explicit.)
    function scan(cands) {
      var found = [];
      for (var i = 0; i < cands.length; i++) {
        var sc = scoreRow(cands[i], qtokens, qjoined, near);
        if (sc > 0) found.push({ row: cands[i], s: sc });
      }
      return found;
    }
    var out = scan(IDX.buckets[qjoined.charAt(0)] || []);
    /* An airport code is bucketed under the AIRPORT'S NAME, not the code, and the widening
       pass below cannot rescue it because every IATA code is 3 characters and that pass wants
       4. Measured before this line existed: 8 of 25 major US codes returned NOTHING (MCO, EWR,
       BNA, MSY, DCA, IAD, MDW, HNL) and "ORD" returned Ord, Nebraska — population 2,000 — with
       O'Hare absent. A wrong stop that looks right is worse than no result, so the code is
       looked up directly and scored above everything the letter bucket found. */
    var air = IDX.codes[qjoined];
    if (air) out.push({ row: air, s: 1000 });
    /* …but a code must not bury a SUBSTANTIAL city that is genuinely spelled that way. Measured
       against this index, 69 codes are also city names: PALU is a city of 398,000 in Indonesia
       and the ICAO of a radar station in Alaska; ABA is a Nigerian city of 1.2 million and
       Abakan's IATA; LIRA is a Ugandan city and Rome Ciampino.
       Prominence is the test, NOT exactness. "Any exact name match wins" was tried first and
       put Ord, Nebraska — population 2,000 — back above O'Hare, which is the defect this whole
       branch exists to fix.
       The city has to out-weigh THE AIRPORT IT COLLIDES WITH, on the weight scale the index
       already shares between them (log10 population for cities, size band for airports). A
       fixed population threshold was tried too and it is the wrong instrument: San, in Mali,
       has a population of exactly 100,000, so any round number lands on top of it and decides
       San Diego by a rounding artefact.
       And it ADDS rather than assigns, because assigning a flat rank flattened the several
       Portlands to equal scores and the near-anchor stopped deciding between them — the
       proximity bonus is already inside `s` and has to survive. */
    if (air) for (var oi = 0; oi < out.length; oi++)
      if (out[oi].row.n === qjoined && out[oi].row.w > air.w) out[oi].s += 1000;
    if (out.length < 3 && qtokens[0].length >= 4) {
      var wide = scan(IDX.rows);
      if (wide.length > out.length) { out = wide; if (air) out.push({ row: air, s: 1000 }); }
    }
    out.sort(function (a, b) { return b.s - a.s; });
    var top = [], seen = {};
    for (var k = 0; k < out.length && top.length < MAX_LOCAL; k++) {
      var r = out[k].row;
      var key = r.n + "|" + r.region + "|" + r.cc;
      if (seen[key]) continue;
      seen[key] = 1;
      top.push(r);
    }
    return top;
  }

  /* what the list shows, and what picking it writes into the trip, per kind of row */
  /* `kind` RIDES ALONG NOW. It was computed, used to rank, and then dropped one line before the
     caller could see it — so nothing downstream could tell an airport from a town, and a leg
     between two airports was drawn as a car journey. It costs one field. */
  function present(r) {
    if (r.iata) return {
      main: r.iata + " · " + r.name,
      sub: (r.region ? r.region + (countryName(r.cc) ? ", " : "") : "") + countryName(r.cc),
      pick: r.iata + " — " + r.name, lat: r.lat, lng: r.lng, kind: r.kind || "a"
    };
    var where = r.cc === "US" ? r.region : countryName(r.cc);
    return {
      main: r.name, sub: where,
      pick: r.name + (where ? ", " + where : ""), lat: r.lat, lng: r.lng, kind: r.kind
    };
  }

  function el(tag, cls, text) {
    var e = document.createElement(tag);
    if (cls) e.className = cls;
    if (text != null) e.textContent = text;
    return e;
  }

  function attachSuggest(input, opts) {
    opts = opts || {};
    var onPick = opts.onPick || function () {};
    var minChars = opts.minChars || 2;
    var host = opts.anchor || input.parentNode;
    if (!input || !host) return { destroy: function () {} };

    var box = el("div", "sg-list");
    box.setAttribute("role", "listbox");
    box.hidden = true;
    if (getComputedStyle(host).position === "static") host.style.position = "relative";
    host.appendChild(box);

    var netTimer = null, seq = 0, shown = [], cursor = -1;

    input.setAttribute("autocomplete", "off");
    input.setAttribute("role", "combobox");
    input.setAttribute("aria-expanded", "false");
    input.setAttribute("aria-autocomplete", "list");
    // Warm the index when the browser goes idle — a page with a place field on it will very
    // likely use it, and fetching during idle keeps the one-time ~1s parse out of the first
    // keystroke. Focus stays as the fallback for browsers without requestIdleCallback.
    if (typeof requestIdleCallback === "function") requestIdleCallback(loadIndex, { timeout: 4000 });
    input.addEventListener("focus", function () { loadIndex(); }, { once: true });

    function close() {
      box.hidden = true; box.innerHTML = ""; shown = []; cursor = -1;
      input.setAttribute("aria-expanded", "false");
    }
    function choose(i) {
      var p = shown[i];
      if (!p) return;
      input.value = p.pick;
      close();
      onPick({ name: p.pick, lat: p.lat, lng: p.lng, kind: p.kind || null });
    }
    function mark() {
      Array.prototype.forEach.call(box.children, function (c, i) {
        c.classList.toggle("on", i === cursor);
        c.setAttribute("aria-selected", i === cursor ? "true" : "false");
      });
    }
    function render() {
      box.innerHTML = "";
      if (!shown.length) { close(); return; }
      shown.forEach(function (p, i) {
        var b = el("button", "sg-item");
        b.type = "button";
        b.setAttribute("role", "option");
        b.appendChild(el("span", "sg-name", p.main));
        if (p.sub) b.appendChild(el("span", "sg-full", p.sub));
        // mousedown, not click: blur would close the list before a click could land.
        b.addEventListener("mousedown", function (e) { e.preventDefault(); choose(i); });
        b.addEventListener("touchstart", function (e) { e.preventDefault(); choose(i); }, { passive: false });
        box.appendChild(b);
      });
      cursor = -1;
      box.hidden = false;
      input.setAttribute("aria-expanded", "true");
      mark();
    }

    /* Nominatim, appended under what the local index already showed — the long tail of
       street addresses and POIs. It never reorders the top: results jumping under a finger
       mid-tap is how the wrong place ends up in a trip. */
    function netLook(q) {
      var mine = ++seq;
      fetch("/api/geocode?q=" + encodeURIComponent(q), { headers: { accept: "application/json" } })
        .then(function (r) { return r.ok ? r.json() : { results: [] }; })
        .then(function (j) {
          if (mine !== seq) return;
          if (input.value.trim() !== q) return;      // they kept typing; this answer is stale
          var extra = [];
          (j.results || []).forEach(function (p) {
            if (extra.length >= MAX_NET) return;
            var dup = shown.some(function (s) {
              return Math.hypot(s.lat - p.lat, s.lng - p.lon) < 0.03 ||
                     norm(s.pick).indexOf(norm(p.name).split(",")[0]) === 0;
            });
            if (!dup) extra.push({ main: p.name, sub: p.full !== p.name ? p.full : "",
                                   pick: p.name, lat: p.lat, lng: p.lon });
          });
          if (extra.length) { shown = shown.slice(0, MAX_LOCAL).concat(extra); render(); }
          else if (!shown.length) close();
        })
        .catch(function () {});
    }

    function look() {
      var q = input.value.trim();
      clearTimeout(netTimer);
      if (q.length < minChars) { close(); return; }
      var near = opts.near && opts.near();
      var run = function () {
        shown = searchLocal(q, near).map(present);
        render();
        if (q.length >= NET_MIN)
          netTimer = setTimeout(function () { netLook(q); }, NET_DEBOUNCE);
      };
      if (IDX) run();
      else loadIndex().then(function () { if (input.value.trim() === q) run(); });
    }

    input.addEventListener("input", look);
    input.addEventListener("keydown", function (e) {
      if (box.hidden) {
        if (e.key === "Enter" && input.value.trim().length >= minChars) { e.preventDefault(); look(); }
        return;
      }
      if (e.key === "ArrowDown") { e.preventDefault(); cursor = Math.min(cursor + 1, shown.length - 1); mark(); }
      else if (e.key === "ArrowUp") { e.preventDefault(); cursor = Math.max(cursor - 1, 0); mark(); }
      else if (e.key === "Enter") { e.preventDefault(); choose(cursor < 0 ? 0 : cursor); }
      else if (e.key === "Escape") { e.preventDefault(); close(); }
    });
    input.addEventListener("blur", function () { setTimeout(close, 120); });

    return { destroy: function () { clearTimeout(netTimer); close(); if (box.parentNode) box.parentNode.removeChild(box); } };
  }

  var CSS = [
    ".sg-list{position:absolute;left:0;right:0;top:calc(100% + 4px);z-index:400;",
    "  background:var(--card,#fff);border:2px solid var(--ink,#141414);border-radius:12px;",
    "  box-shadow:0 12px 30px rgba(0,0,0,.24);overflow:hidden;max-height:264px;overflow-y:auto}",
    ".sg-list[hidden]{display:none}",
    /* ONE LINE PER PLACE, 44px, because a phone with the keyboard up has ~165px of list.
       Stacked name-over-region made each row 78px, so "evan" offered THREE results at 390x664
       and two once iOS raises the keyboard — on the input this product now opens with. Flat
       rows put five or six in the same space. The row is still 44px, so nothing about the tap
       target changes; only the stacking does. */
    ".sg-item{display:flex;align-items:center;gap:8px;width:100%;text-align:left;background:none;border:0;cursor:pointer;",
    "  padding:6px 13px;min-height:44px;font:inherit;color:var(--ink,#141414);",
    "  border-bottom:1px solid var(--line,#E4E1D8)}",
    ".sg-item:last-child{border-bottom:0}",
    ".sg-item.on,.sg-item:hover{background:var(--sheet,#FCFBF8)}",
    ".sg-name{flex:0 1 auto;font-weight:600;font-size:15px;",
    "  overflow:hidden;text-overflow:ellipsis;white-space:nowrap}",
    ".sg-full{flex:1 1 auto;min-width:0;font-size:12.5px;opacity:.62;",
    "  overflow:hidden;text-overflow:ellipsis;white-space:nowrap}"
  ].join("");

  function injectCss() {
    if (document.getElementById("sg-css")) return;
    var s = document.createElement("style");
    s.id = "sg-css"; s.textContent = CSS;
    document.head.appendChild(s);
  }
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", injectCss);
  else injectCss();

  /* ── nearestPlace: snap a coarse map tap to a real place (§2z) ────────────────────────────
   *
   * The analysis behind /new?snap=1: the cold start was never too many taps, it was that a
   * COARSE tap is punished. Reverse geocoding is pinned at `zoom => 14` (lib/geocode.php), and
   * at map-zoom 4 a thumb covers ±100km — so it faithfully names the hamlet under the error and
   * a tap aimed at Chicago comes back "Stickney Township". People then pinch in to be precise,
   * and THAT is what breaks the second tap, because the destination is now off screen. Snapping
   * removes the reason to zoom in at all.
   *
   * The caller passes a radius in DEGREES OF LATITUDE, because only it knows the zoom — /new
   * derives it by projecting a point N screen pixels above the tap, so the radius is whatever
   * the thumb actually covered. Coarse zoom therefore snaps to prominent places and close zoom
   * to small ones, which is the behaviour you want and falls out for free.
   *
   * CITIES BEAT AIRPORTS, and an airport wins only when no city is in range. Airport rows carry
   * a flat-ish weight (median 38, max 50) that beats most towns outright, so a rank on weight
   * alone turns a tap at the edge of a metro into "XYZ — Podunk Regional Airport". You tap a
   * PLACE; if you want the airport you type its code, which already works (D-111/D-112).
   *
   * RANKED BY `weight − (fraction of the thumb's reach)`, which is one line and was chosen from
   * measured numbers rather than taste. Ranking on weight ALONE was the first cut and it failed
   * a case worth keeping: a tap on Tahoe City at zoom 4 returned **Sacramento, 133km away**,
   * because Sacramento (5.7) outweighs Reno (5.4) and a 182km radius reaches both. You aimed at
   * the Sierra and got the Central Valley. Subtracting the distance as a FRACTION OF THE RADIUS
   * fixes it without a tuned constant: Reno 5.4−0.27 = 5.13 beats Sacramento 5.7−0.73 = 4.97,
   * while Chicago 6.4−0.02 = 6.38 still crushes Milwaukee 5.8−0.75 = 5.05 for a tap on Chicago.
   * Weights span roughly 3.0–7.4, so "the edge of your thumb costs one weight point" is a real
   * penalty that still cannot let a hamlet under the finger beat a metro at arm's length — and
   * at zoom 4 you cannot be aiming at a hamlet anyway.
   *
   * Because the penalty is a fraction, it rescales with the zoom for free, which is the same
   * reason the radius is derived from pixels rather than being a fixed kilometre count.
   *
   * Returns null and never throws when the index has not loaded — no snap is always safe,
   * because the reverse-geocode path it replaces is still there underneath.
   */
  function nearestPlace(lat, lng, radiusDeg) {
    if (!IDX || !(radiusDeg > 0)) return null;
    var k = Math.cos(lat * Math.PI / 180); if (!(k > 1e-6)) k = 1e-6;
    var lngR = radiusDeg / k;
    var rows = IDX.rows;
    var city = null, cityS = -Infinity, air = null, airS = -Infinity;
    for (var i = 0; i < rows.length; i++) {
      var r = rows[i];
      var dLat = r.lat - lat; if (dLat > radiusDeg || dLat < -radiusDeg) continue;
      var dLng = r.lng - lng; if (dLng > lngR || dLng < -lngR) continue;
      var ex = dLng * k, d = Math.sqrt(dLat * dLat + ex * ex);
      if (d > radiusDeg) continue;                       // a circle, not the bounding box
      var score = r.w - (d / radiusDeg);
      if (r.kind === "a") { if (score > airS)  { air  = r; airS  = score; } }
      else                { if (score > cityS) { city = r; cityS = score; } }
    }
    var best = city || air;
    if (!best) return null;
    // present().pick is what picking a suggestion already writes into a trip, so a snapped tap
    // and a typed pick name the same place the same way.
    return { name: present(best).pick, lat: best.lat, lng: best.lng, kind: best.kind, w: best.w };
  }

  global.attachSuggest = attachSuggest;
  global.nearestPlace  = nearestPlace;
  /* The index is lazy-loaded on first focus, which is too late for a tap. A caller that intends
     to snap warms it at boot; the promise is shared, so this costs one fetch either way. */
  global.placesReady   = loadIndex;
})(window);
